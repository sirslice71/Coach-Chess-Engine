const UCI_HASH_DEFAULT_MB = 32;
const UCI_HASH_MIN_MB = 1;
const UCI_HASH_MAX_MB = 512;
const UCI_MOVE_OVERHEAD_DEFAULT_MS = 50;
const UCI_MOVE_OVERHEAD_MIN_MS = 0;
const UCI_MOVE_OVERHEAD_MAX_MS = 1000;
const UCI_MAX_MOVES_TO_GO = 100;

//----------------------------------
// Time Management: Game Phase
//
// Cheap phase estimate used only when
// movestogo is not supplied by the GUI.
// Primary signal is material (board.whiteMaterial
// / board.blackMaterial already exclude kings).
// fullMoveNumber is a secondary, even cheaper
// signal: a low move number is treated as
// "opening" even if material already looks
// lighter than the opening floor (e.g. an
// early trade-heavy line), since there is
// still a full game and clock ahead.
//----------------------------------

const STARTING_MATERIAL_TOTAL =
    2 * (8 * 100 + 2 * 300 + 2 * 310 + 2 * 500 + 900); // 7840

const OPENING_MATERIAL_FLOOR =
    STARTING_MATERIAL_TOTAL * 0.85;

const MIDDLEGAME_MATERIAL_FLOOR =
    STARTING_MATERIAL_TOTAL * 0.60;

const LATE_MIDDLEGAME_MATERIAL_FLOOR =
    STARTING_MATERIAL_TOTAL * 0.35;

const MOVES_TO_GO_BY_PHASE = {
    opening: 30,
    middlegame: 24,
    lateMiddlegame: 19,
    endgame: 15
};

const OPENING_FULLMOVE_FLOOR = 10;

export function gamePhase(
    totalMaterial = STARTING_MATERIAL_TOTAL,
    fullMoveNumber = 1
) {

    if (
        fullMoveNumber <= OPENING_FULLMOVE_FLOOR ||
        totalMaterial >= OPENING_MATERIAL_FLOOR
    ) {
        return "opening";
    }

    if (totalMaterial >= MIDDLEGAME_MATERIAL_FLOOR) {
        return "middlegame";
    }

    if (totalMaterial >= LATE_MIDDLEGAME_MATERIAL_FLOOR) {
        return "lateMiddlegame";
    }

    return "endgame";

}

export function estimateMovesToGo({
    totalMaterial = STARTING_MATERIAL_TOTAL,
    fullMoveNumber = 1
} = {}) {

    return MOVES_TO_GO_BY_PHASE[
        gamePhase(totalMaterial, fullMoveNumber)
    ];

}

//----------------------------------
// Time Management: Complexity Multiplier
//
// Cheap signals only:
// - in check (already computed by caller)
// - legal move count (already generated by caller)
// - capture count (flag check, no make/undo)
// - game phase (material-based)
//
// "Checks available" is intentionally NOT counted:
// it would require a make/undo cycle per candidate
// move, which is not cheap enough to justify here.
//----------------------------------

const COMPLEXITY_MAX_MULTIPLIER = 1.6;

//----------------------------------
// Time Management: Opening Throttle
//
// Arena games with no opening book can lead Coach to spend
// too generously on the first several moves -- time that
// would be better saved for the middlegame. This throttle
// only ever scales the multiplier further DOWN, and only for
// otherwise-quiet opening positions. It is skipped whenever
// any of the cheap tactical-urgency signals below apply, so
// Coach still thinks normally when the opening is sharp.
//
// fullMoveNumber <= 6 gets the strongest throttle; <= 8 gets
// a lighter one; beyond that, normal time management applies
// unchanged. This only affects the clock-based ("go wtime/
// btime") path, since that is the only caller of
// complexityMultiplier() -- "go depth", "go movetime", and
// Analysis Lab's fixed-movetime runs never reach this code.
//
// Recalibration (Arena 5-minute no-increment evidence): the
// factors below (0.60 / 0.80) and the capture-count escape
// threshold (3) were still letting Coach spend far too much on
// the first few quiet moves -- move 1 alone took ~6s, and a
// perfectly normal quiet developing position (e.g. after 1.e4 e5
// 2.Nf3 Nc6 3.Bb5 a6) usually has 3+ pseudo-available pawn/piece
// captures on the board without being remotely tactical, which
// was enough to trip isTacticallyUrgent and skip the throttle
// entirely. That let roughly the first 5 moves burn ~32s combined
// before the middlegame even started. The factors are now lower
// (0.30 / 0.55, targeting ~2-4s for move 1 on a 5-minute clock)
// and the capture-count escape threshold is raised to 5, so only
// positions with genuinely many captures on the board (not just
// "a few pawns can trade") are treated as tactically urgent this
// early. inCheck and low-legal-move-count still escape the
// throttle unconditionally, exactly as before.
//----------------------------------

const OPENING_THROTTLE_STRONG_FULLMOVE = 6;
const OPENING_THROTTLE_LIGHT_FULLMOVE = 8;
const OPENING_THROTTLE_STRONG_FACTOR = 0.30;
const OPENING_THROTTLE_LIGHT_FACTOR = 0.55;
const OPENING_THROTTLE_LOW_LEGAL_MOVE_COUNT = 8;
const OPENING_THROTTLE_CAPTURE_COUNT = 5;

//----------------------------------
// Time Management: Late-Opening / Middlegame
// Tactical Reinvestment
//
// The opening throttle above only ever scales time DOWN, and
// only for fullMoveNumber <= 8. Once the position reaches the
// late-opening/middlegame window (roughly moves 9-28) and
// still has many pieces on the board, a tactically rich
// position deserves a bit MORE time than the plain phase bonus
// already gives -- this is exactly the kind of position where
// Coach only found the materially better defensive move once
// given a longer fixed movetime (Kh1 over h3 at 20s, but not at
// 5s/10s). This reinvests some of what the opening throttle
// saved earlier in the game, using only signals already
// computed at the call site (no extra move generation or
// make/undo, consistent with the "cheap signals only" rule
// above).
//
// Deliberately additive, well below COMPLEXITY_MAX_MULTIPLIER:
// each signal contributes a modest, fixed amount, and only
// within the fullmove window and only while total material
// shows the position has not already been simplified toward an
// endgame (reusing MIDDLEGAME_MATERIAL_FLOOR, the same threshold
// gamePhase() uses for "middlegame").
//
// A first version of this feature only added flat +0.05
// per-signal bumps across the whole 9-28 window, which moved the
// motivating FEN's allocation from 14992ms to 15617ms on a
// 5-minute clock -- correct in direction, but too small to be
// the difference between h3 and Kh1 the way the 20s-fixed-
// movetime comparison suggested it should be. A second revision
// added a narrower "core" window (moves 15-24) with its own flat
// base boost, plus an extra boost when legal moves are unusually
// high in that core window, which got the motivating FEN to
// ~18.7s. Genuine check/capture pressure is still covered by the
// inCheck/captureCount signals below; a separate king-safety
// (pawn-shield) detector was considered for the "king exposed"
// half of an earlier request, but a reliable version needs extra
// board traversal beyond the "cheap signals only" rule this
// feature has followed throughout, so raw legal-move count is
// used instead as the cheap stand-in for "the position has a lot
// going on."
//
// Recalibration (Arena 5-minute no-increment evidence): with the
// opening throttle now cutting deeper (see above), there is more
// saved clock time to reinvest, and the Arena games showed New
// Coach was still carrying too much of it past move 10 without
// spending it -- by moves 12-18 it held ~18s more than Old Coach,
// and ~30s more by move 24. The core window is widened from
// 15-24 to 10-28 (matching "roughly moves 10-28" from the
// motivating request) so moves 10-14 also get the full core
// boost instead of just the smaller flat per-signal bumps below.
// This does not change the motivating move-19 FEN's allocation
// (19 was already inside the old 15-24 core window), and a
// simplified endgame that happens to fall in this range still
// gets nothing, because manyPiecesRemain is checked before any
// of this -- widening the fullmove range does not weaken that
// material gate.
//----------------------------------

const LATE_TACTICAL_FULLMOVE_MIN = 9;
const LATE_TACTICAL_FULLMOVE_MAX = 28;
const LATE_TACTICAL_LEGAL_MOVE_COUNT = 20;
const LATE_TACTICAL_SIGNAL_BONUS = 0.05;

const LATE_TACTICAL_CORE_FULLMOVE_MIN = 10;
const LATE_TACTICAL_CORE_FULLMOVE_MAX = 28;
const LATE_TACTICAL_CORE_BASE_BONUS = 0.15;
const LATE_TACTICAL_HIGH_LEGAL_MOVE_COUNT = 25;
const LATE_TACTICAL_HIGH_MOBILITY_BONUS = 0.10;

function lateOpeningMiddlegameBonus({
    fullMoveNumber,
    totalMaterial,
    legalMoveCount,
    captureCount,
    inCheck
}) {

    const inWindow =
        fullMoveNumber >= LATE_TACTICAL_FULLMOVE_MIN &&
        fullMoveNumber <= LATE_TACTICAL_FULLMOVE_MAX;

    const manyPiecesRemain =
        totalMaterial >= MIDDLEGAME_MATERIAL_FLOOR;

    if (!inWindow || !manyPiecesRemain) {
        return 0;
    }

    let bonus = 0;

    if (legalMoveCount >= LATE_TACTICAL_LEGAL_MOVE_COUNT) {
        bonus += LATE_TACTICAL_SIGNAL_BONUS;
    }

    if (captureCount >= 1) {
        bonus += LATE_TACTICAL_SIGNAL_BONUS;
    }

    if (inCheck) {
        bonus += LATE_TACTICAL_SIGNAL_BONUS;
    }

    const inCoreWindow =
        fullMoveNumber >= LATE_TACTICAL_CORE_FULLMOVE_MIN &&
        fullMoveNumber <= LATE_TACTICAL_CORE_FULLMOVE_MAX;

    if (inCoreWindow) {

        bonus += LATE_TACTICAL_CORE_BASE_BONUS;

        if (legalMoveCount >= LATE_TACTICAL_HIGH_LEGAL_MOVE_COUNT) {
            bonus += LATE_TACTICAL_HIGH_MOBILITY_BONUS;
        }

    }

    return bonus;

}

export function complexityMultiplier({
    inCheck = false,
    legalMoveCount = 0,
    captureCount = 0,
    totalMaterial = STARTING_MATERIAL_TOTAL,
    fullMoveNumber = 1,
    remainingTime = Infinity
} = {}) {

    let multiplier = 1.0;

    if (inCheck) {
        multiplier += 0.15;
    }

    if (legalMoveCount >= 35) {
        multiplier += 0.20;
    }
    else if (legalMoveCount >= 25) {
        multiplier += 0.10;
    }

    if (captureCount >= 6) {
        multiplier += 0.15;
    }
    else if (captureCount >= 3) {
        multiplier += 0.08;
    }

    const phase = gamePhase(totalMaterial, fullMoveNumber);

    if (phase === "middlegame" || phase === "lateMiddlegame") {
        multiplier += 0.10;
    }

    multiplier +=
        lateOpeningMiddlegameBonus({
            fullMoveNumber,
            totalMaterial,
            legalMoveCount,
            captureCount,
            inCheck
        });

    multiplier =
        Math.min(multiplier, COMPLEXITY_MAX_MULTIPLIER);

    //----------------------------------
    // Never let complexity amplify spend
    // when the clock itself is already low.
    //----------------------------------

    if (remainingTime <= 3000) {
        multiplier = Math.min(multiplier, 1.05);
    }
    else if (remainingTime <= 8000) {
        multiplier = Math.min(multiplier, 1.20);
    }

    //----------------------------------
    // Opening throttle. Checked directly against the same
    // cheap signals used above (in check, very few legal
    // moves, several captures already on the board) rather
    // than "multiplier > 1.0", because the existing mobility
    // bump (legalMoveCount >= 25) fires on almost every normal
    // opening position -- a typical opening has 20-30 legal
    // moves, so treating that alone as "urgent" would defeat
    // the throttle for nearly every game. Only genuine
    // tactical signals skip it.
    //----------------------------------

    const isTacticallyUrgent =
        inCheck ||
        legalMoveCount <= OPENING_THROTTLE_LOW_LEGAL_MOVE_COUNT ||
        captureCount >= OPENING_THROTTLE_CAPTURE_COUNT;

    if (!isTacticallyUrgent) {

        if (fullMoveNumber <= OPENING_THROTTLE_STRONG_FULLMOVE) {
            multiplier *= OPENING_THROTTLE_STRONG_FACTOR;
        }
        else if (fullMoveNumber <= OPENING_THROTTLE_LIGHT_FULLMOVE) {
            multiplier *= OPENING_THROTTLE_LIGHT_FACTOR;
        }

    }

    return multiplier;

}

function withMutedConsole(fn) {

    const original = {
        clear: console.clear,
        error: console.error,
        log: console.log,
        table: console.table,
        trace: console.trace,
        warn: console.warn
    };

    console.clear = () => {};
    console.error = () => {};
    console.log = () => {};
    console.table = () => {};
    console.trace = () => {};
    console.warn = () => {};

    try {

        return fn();

    }

    finally {

        console.clear = original.clear;
        console.error = original.error;
        console.log = original.log;
        console.table = original.table;
        console.trace = original.trace;
        console.warn = original.warn;

    }

}

export function createEngineCore(fen = null) {

    const board = new Board();
    const search =
        new Search(
            board,
            new LegalMoveGenerator(
                board,
                new MoveGenerator(board)
            ),
            new Evaluation(board)
        );

    const moveGenerator =
        search.legalMoveGenerator.moveGenerator;

    const legalMoveGenerator =
        search.legalMoveGenerator;

    const evaluation =
        search.evaluation;

    if (fen && fen !== "startpos") {
        FEN.import(board, fen);
    }
    else {
        board.hashKey =
            search.zobrist.generate(board);
    }

    return {
        board,
        evaluation,
        legalMoveGenerator,
        moveGenerator,
        search
    };

}

function promotionSuffix(piece) {

    switch (Math.abs(piece)) {

        case Math.abs(Piece.WQ):
            return "q";

        case Math.abs(Piece.WR):
            return "r";

        case Math.abs(Piece.WB):
            return "b";

        case Math.abs(Piece.WN):
            return "n";

        default:
            return "";

    }

}

export function moveToUci(move) {

    let uci =
        algebraic(move.fromSquare) +
        algebraic(move.toSquare);

    if (move.isPromotion()) {
        uci += promotionSuffix(move.promotedPiece);
    }

    return uci;

}

export function uciToMove(uciString, legalMoves) {

    const normalized =
        uciString.trim().toLowerCase();

    return legalMoves.find(move =>
        moveToUci(move) === normalized
    ) || null;

}

export function applyUciMove(engine, uciString) {

    const legalMoves =
        engine.legalMoveGenerator.generateMoves();

    const move =
        uciToMove(
            uciString,
            legalMoves
        );

    if (!move) {

        throw new Error(
            `Illegal UCI move: ${uciString}`
        );

    }

    engine.board.makeMove(move);

    return move;

}

export function allocateMoveTime({
    sideToMove,
    wtime = 0,
    btime = 0,
    winc = 0,
    binc = 0,
    moveOverheadMs = UCI_MOVE_OVERHEAD_DEFAULT_MS,
    movestogo = null,

    //----------------------------------
    // Optional position-complexity context.
    // Every field defaults to a neutral value
    // that reproduces the original (pre-time-
    // management-upgrade) allocation exactly,
    // so existing callers that don't supply
    // this context see unchanged behavior.
    //----------------------------------

    fullMoveNumber = 1,
    totalMaterial = STARTING_MATERIAL_TOTAL,
    inCheck = false,
    legalMoveCount = 0,
    captureCount = 0
}) {

    const remainingTime =
        sideToMove > 0 ? wtime : btime;

    const increment =
        sideToMove > 0 ? winc : binc;

    if (remainingTime <= 0) {
        return 1;
    }

    const overhead =
        Math.max(
            UCI_MOVE_OVERHEAD_MIN_MS,
            Math.min(
                UCI_MOVE_OVERHEAD_MAX_MS,
                Math.floor(moveOverheadMs)
            )
        );

    const safetyBuffer =
        remainingTime > 1000 ? 100 : 50;

    const reservedTime =
        safetyBuffer + overhead;

    const usableTime =
        Math.max(1, remainingTime - reservedTime);

    const movesToGo =
        Number.isInteger(movestogo) &&
        movestogo > 0
            ? Math.min(
                UCI_MAX_MOVES_TO_GO,
                movestogo
            )
            : estimateMovesToGo({ totalMaterial, fullMoveNumber });

    const multiplier =
        complexityMultiplier({
            inCheck,
            legalMoveCount,
            captureCount,
            totalMaterial,
            fullMoveNumber,
            remainingTime
        });

    const base =
        (usableTime / movesToGo) * multiplier;

    const incrementPart =
        increment * 0.75;

    let minimumFloor = 50;

    if (remainingTime <= 500) {
        minimumFloor = 10;
    }
    else if (remainingTime <= 2000) {
        minimumFloor = 25;
    }

    const minimumBudget =
        Math.min(
            usableTime,
            minimumFloor
        );

    //----------------------------------
    // Percentage-of-clock cap. Scales with
    // the same complexity multiplier so
    // genuinely complex positions can use a
    // larger slice, but is hard-capped so a
    // single move can never eat too much of
    // the remaining clock (avoids flagging).
    //----------------------------------

    const maxPercentage =
        Math.min(
            0.20,
            0.10 * multiplier
        );

    const maximumBudget =
        Math.max(
            minimumBudget,
            Math.floor(usableTime * maxPercentage)
        );

    const rawBudget =
        Math.floor(base + incrementPart);

    return Math.max(
        1,
        Math.min(
            maximumBudget,
            Math.max(minimumBudget, rawBudget)
        )
    );

}

function clampHashSize(value) {

    if (!Number.isFinite(value)) {
        return UCI_HASH_DEFAULT_MB;
    }

    return Math.max(
        UCI_HASH_MIN_MB,
        Math.min(
            UCI_HASH_MAX_MB,
            Math.floor(value)
        )
    );

}

function clampMoveOverhead(value, fallback = UCI_MOVE_OVERHEAD_DEFAULT_MS) {

    if (!Number.isFinite(value)) {
        return fallback;
    }

    return Math.max(
        UCI_MOVE_OVERHEAD_MIN_MS,
        Math.min(
            UCI_MOVE_OVERHEAD_MAX_MS,
            Math.floor(value)
        )
    );

}

function parseSetOption(tokens) {

    const nameIndex =
        tokens.indexOf("name");

    if (nameIndex === -1) {
        return null;
    }

    const valueIndex =
        tokens.indexOf("value");

    const nameTokens =
        valueIndex === -1
            ? tokens.slice(nameIndex + 1)
            : tokens.slice(nameIndex + 1, valueIndex);

    const valueTokens =
        valueIndex === -1
            ? []
            : tokens.slice(valueIndex + 1);

    return {
        name: nameTokens.join(" ").trim(),
        value: valueTokens.join(" ").trim()
    };

}

//----------------------------------
// UCI score formatting.
//
// search.js encodes forced mates as a root-relative
// centipawn-shaped value: the side being mated returns
// "-MATE + ply", and negamax's repeated negation on the way
// back to the root turns a winning mate line into
// "MATE - ply" automatically -- no separate "delivering
// mate" code path is needed. Here "ply" is the number of
// plies from the root to the terminal (no legal moves, in
// check) node, since search.js increments ply by exactly 1
// on every recursive call starting from ply = 0 at the root.
//
// Previously this score was always sent to the GUI as a raw
// "score cp" value, even when it was mate-class (e.g. 99994
// for a mate found 6 plies deep). Some GUIs -- Arena
// included -- apply their own heuristics to abnormally large
// cp scores and can render nonsense like "mate in 500" as a
// result. The UCI protocol has a dedicated field for this
// ("score mate N", N = full moves to mate, negative if the
// engine is losing) that every compliant GUI already knows
// how to display correctly, so genuine mate scores should
// always be sent that way instead of guessed at downstream.
//
// Ply-to-move conversion: UCI wants moves, not plies. If the
// side to move at the root can deliver mate, the mating move
// itself is always the odd ply (1, 3, 5, ...), so the move
// count is ceil(plies / 2) -- e.g. plies = 1 -> mate in 1,
// plies = 3 -> mate in 2. The same formula applies when the
// root side is the one getting mated (plies = 2 -> mated in
// 1, plies = 4 -> mated in 2); only the sign differs. This
// avoids an off-by-one because it is derived directly from
// "how many of that side's own moves are still needed",
// not from halving the ply count.
//----------------------------------

function formatUciScore(scoreCp) {

    if (Math.abs(scoreCp) < SearchConstants.MATE_THRESHOLD) {
        return ["cp", scoreCp];
    }

    const pliesToMate =
        SearchConstants.MATE - Math.abs(scoreCp);

    const movesToMate =
        Math.ceil(pliesToMate / 2);

    return [
        "mate",
        scoreCp > 0 ? movesToMate : -movesToMate
    ];

}

export class UciSession {

    constructor() {

        this.quitRequested = false;
        this.debugEnabled = false;
        this.hashSizeMB = UCI_HASH_DEFAULT_MB;
        this.moveOverheadMs =
            UCI_MOVE_OVERHEAD_DEFAULT_MS;

        //----------------------------------
        // Tracked fullmove number for clock-based time
        // management. board.fullMoveNumber is set correctly by
        // Board's constructor and by FEN.import(), but
        // board.makeMove() never increments it -- it only saves
        // the old value into undo history. Since a real UCI GUI
        // resends the *entire* move list on every "position"
        // command (not just the newest move), that means
        // board.fullMoveNumber would silently stay pinned at
        // whatever it was after "position ... [fen]" for the rest
        // of the game, no matter how many moves get replayed on
        // top of it. That would make every fullMoveNumber-based
        // rule in complexityMultiplier() (the opening throttle,
        // the late-opening/middlegame reinvestment window) think
        // every move of the game is still move 1 -- consistent
        // with the Arena evidence motivating this recalibration:
        // Coach's time surplus over Old Coach only ever grew,
        // exactly what happens if the reinvestment window can
        // never fire. This is tracked independently here, at the
        // UCI layer only, rather than fixing board.js itself,
        // which is out of scope for a clock-based time-management
        // change.
        //----------------------------------

        this.currentFullMoveNumber = 1;

        this.resetEngine();

    }

    resetEngine(fen = null) {

        this.engine =
            createEngineCore(fen);

        this.engine.search.tt =
            new TranspositionTable(
                this.hashSizeMB
            );

        this.currentFullMoveNumber =
            this.engine.board.fullMoveNumber;

    }

    handleCommand(line) {

        const trimmed = line.trim();

        if (!trimmed) {
            return [];
        }

        const tokens =
            trimmed.split(/\s+/);

        const command = tokens[0];

        switch (command) {

            case "uci":

                return [
                    "id name Coach Chess Engine",
                    "id author Sir Slice",
                    `option name Hash type spin default ${UCI_HASH_DEFAULT_MB} min ${UCI_HASH_MIN_MB} max ${UCI_HASH_MAX_MB}`,
                    `option name Move Overhead type spin default ${UCI_MOVE_OVERHEAD_DEFAULT_MS} min ${UCI_MOVE_OVERHEAD_MIN_MS} max ${UCI_MOVE_OVERHEAD_MAX_MS}`,
                    "option name Clear Hash type button",
                    "uciok"
                ];

            case "isready":

                return ["readyok"];

            case "ucinewgame":

                this.resetEngine();
                return [];

            case "stop":

                //----------------------------------
                // Search is synchronous today, so a
                // later stdin stop command cannot
                // interrupt an already-running search.
                // When idle, stop is a harmless no-op.
                //----------------------------------

                return [];

            case "ponderhit":

                return [];

            case "setoption":

                return this.handleSetOption(
                    tokens.slice(1)
                );

            case "debug":

                this.debugEnabled =
                    tokens[1] === "on";

                return [];

            case "register":

                return [];

            case "position":

                this.handlePosition(tokens.slice(1));
                return [];

            case "go":

                return this.handleGo(tokens.slice(1));

            case "quit":

                this.quitRequested = true;
                return [];

            default:

                return [];

        }

    }

    handlePosition(tokens) {

        const movesIndex =
            tokens.indexOf("moves");

        const moveTokens =
            movesIndex === -1
                ? []
                : tokens.slice(movesIndex + 1);

        if (tokens[0] === "startpos") {

            this.resetEngine();

        }

        else if (tokens[0] === "fen") {

            const fenTokens =
                movesIndex === -1
                    ? tokens.slice(1)
                    : tokens.slice(1, movesIndex);

            this.resetEngine(
                fenTokens.join(" ")
            );

        }

        else {

            throw new Error(
                `Unsupported position command: ${tokens.join(" ")}`
            );

        }

        //----------------------------------
        // Capture the starting fullmove number and side to move
        // right after the reset (correct at this point, whether
        // from a fresh startpos or an imported FEN), before
        // replaying moveTokens -- board.makeMove() will not
        // advance board.fullMoveNumber itself. See the comment in
        // the constructor above.
        //----------------------------------

        const startingFullMoveNumber =
            this.engine.board.fullMoveNumber;

        const startingSideToMove =
            this.engine.board.sideToMove;

        for (const moveText of moveTokens) {
            applyUciMove(this.engine, moveText);
        }

        const pliesApplied = moveTokens.length;

        const blackMovesCompleted =
            startingSideToMove > 0
                ? Math.floor(pliesApplied / 2)
                : Math.ceil(pliesApplied / 2);

        this.currentFullMoveNumber =
            startingFullMoveNumber + blackMovesCompleted;

    }

    handleSetOption(tokens) {

        const option =
            parseSetOption(tokens);

        if (!option) {
            return [];
        }

        if (option.name === "Hash") {

            const sizeMB =
                clampHashSize(
                    Number.parseInt(
                        option.value,
                        10
                    )
                );

            this.hashSizeMB = sizeMB;

            this.engine.search.tt =
                new TranspositionTable(sizeMB);

            return [];

        }

        if (option.name === "Move Overhead") {

            this.moveOverheadMs =
                clampMoveOverhead(
                    Number.parseInt(
                        option.value,
                        10
                    ),
                    this.moveOverheadMs
                );

            return [];

        }

        if (option.name === "Clear Hash") {

            withMutedConsole(() =>
                this.engine.search.tt.clear()
            );

            return [];

        }

        return [];

    }

    //----------------------------------
    // Run a search call defensively, for exactly one
    // known, narrow failure mode -- nothing broader.
    //
    // js/engine/search.js searchRoot() calls
    // checkSearchDeadline() once at the very top of its
    // iterative-deepening loop (before depth 1 begins),
    // OUTSIDE the try/catch that normally handles
    // SearchTimeout for every other deadline check inside
    // the loop. If the deadline has already elapsed
    // before that first check (an extremely small
    // movetime or near-zero clock budget, e.g. malformed
    // input like "go wtime abc btime 60000"), SearchTimeout
    // escapes uncaught all the way past uciengine.js.
    //
    // Every other checkSearchDeadline() call site inside
    // searchRoot() (mid-iteration, inside negamax,
    // inside quiescence) is already wrapped by search.js's
    // own try/catch, which breaks the loop and returns a
    // normal completed result -- it never reaches here.
    // So a SearchTimeout that does reach this point can
    // only be that one before-first-iteration case, not a
    // generic "search ran out of time" event.
    //
    // That gap is a search.js issue, out of scope for this
    // change and reported separately. This wrapper only
    // catches that specific, identifiable exception type
    // (SearchTimeout, exported read-only from search.js for
    // this purpose) and falls back to the first available
    // legal move with a fresh static-eval score. Every
    // other exception -- any real engine/board/search bug --
    // is rethrown unchanged so it stays visible to uci.js's
    // top-level handler exactly as before, instead of being
    // silently converted into a fabricated move.
    //----------------------------------

    runSearchSafely(searchFn, fallbackMoves) {

        try {

            return searchFn();

        }

        catch (error) {

            if (
                error instanceof SearchTimeout &&
                fallbackMoves.length > 0
            ) {

                this.engine.search.lastSearchScore =
                    this.engine.evaluation.evaluate().total;

                return {
                    move: fallbackMoves[0],
                    notation: fallbackMoves[0].toString(),
                    depth: 0,
                    nodes: 0,
                    pv: [fallbackMoves[0]]
                };

            }

            throw error;

        }

    }

    handleGo(tokens) {

        if (tokens.includes("infinite")) {

            return [
                "info string Infinite search is not supported in the current synchronous UCI mode",
                "bestmove 0000"
            ];

        }

        if (
            tokens.includes("nodes") ||
            tokens.includes("mate") ||
            tokens.includes("searchmoves") ||
            tokens.includes("ponder")
        ) {

            return [
                "info string This go variant is not supported in the current UCI mode",
                "bestmove 0000"
            ];

        }

        const depthIndex =
            tokens.indexOf("depth");

        const movetimeIndex =
            tokens.indexOf("movetime");

        const wtimeIndex =
            tokens.indexOf("wtime");

        const btimeIndex =
            tokens.indexOf("btime");
        const movestogoIndex =
            tokens.indexOf("movestogo");

        const hasDepth =
            depthIndex !== -1 &&
            depthIndex < tokens.length - 1;

        const hasClock =
            wtimeIndex !== -1 &&
            btimeIndex !== -1 &&
            wtimeIndex < tokens.length - 1 &&
            btimeIndex < tokens.length - 1;

        const hasMovetime =
            movetimeIndex !== -1 &&
            movetimeIndex < tokens.length - 1;

        //----------------------------------
        // Root legal moves are needed up front
        // (not just inside the wtime/btime branch)
        // to guard the zero-legal-move case below
        // for every recognized go variant. Cheap:
        // one call, reused everywhere it's needed.
        // Only computed when some recognized variant
        // is present, so the "unsupported go variant"
        // fallback below is completely unaffected.
        //----------------------------------

        const rootLegalMoves =
            (hasDepth || hasClock || hasMovetime)
                ? this.engine.legalMoveGenerator.generateMoves()
                : [];

        let result = null;

        if (
            (hasDepth || hasClock || hasMovetime) &&
            rootLegalMoves.length === 0
        ) {

            //----------------------------------
            // No legal moves at the root (checkmate
            // or stalemate). search.bestMove() has a
            // latent bug for exactly this case:
            // js/engine/search.js searchRoot() calls
            // result.bestMove.toString() unconditionally
            // while building its per-iteration debug
            // row, even in quiet mode, which throws
            // when bestMove is null. That is a
            // search.js issue -- out of scope for this
            // change and reported separately. Short-
            // circuiting here keeps every recognized
            // "go" variant protocol-safe without
            // touching search.js.
            //----------------------------------

            const inCheck =
                this.engine.board.isInCheck();

            this.engine.search.lastSearchScore =
                inCheck
                    ? this.engine.search.toWhiteRelativeScore(
                        -SearchConstants.MATE,
                        this.engine.board.sideToMove
                    )
                    : SearchConstants.DRAW;

            result = {
                move: null,
                notation: null,
                depth: 0,
                nodes: 0,
                pv: []
            };

        }

        else if (hasDepth) {

            const depth =
                Math.max(
                    1,
                    Number.parseInt(
                        tokens[depthIndex + 1],
                        10
                    ) || 1
                );

            result =
                this.runSearchSafely(
                    () =>
                        withMutedConsole(() =>
                            this.engine.search.bestMove(
                                depth,
                                { quiet: true }
                            )
                        ),
                    rootLegalMoves
                );

        }

        else if (hasClock) {

            //----------------------------------
            // Forced-move shortcut: with exactly
            // one legal move at the root, there is
            // nothing to decide. Running a full
            // iterative-deepening search to a clock
            // deadline would waste clock on a move
            // that isn't actually a choice, which is
            // exactly the "too conservative" behavior
            // this change is meant to reduce. A
            // minimal depth-1 search still gives the
            // info/score/PV plumbing below something
            // real to report, at negligible cost.
            //----------------------------------

            if (rootLegalMoves.length === 1) {

                result =
                    this.runSearchSafely(
                        () =>
                            withMutedConsole(() =>
                                this.engine.search.bestMove(
                                    1,
                                    { quiet: true }
                                )
                            ),
                        rootLegalMoves
                    );

            }

            else {

                const wincIndex =
                    tokens.indexOf("winc");

                const bincIndex =
                    tokens.indexOf("binc");

                const captureCount =
                    rootLegalMoves.filter(
                        move => move.isCapture()
                    ).length;

                const movetime =
                    allocateMoveTime({
                        sideToMove:
                            this.engine.board.sideToMove,
                        wtime:
                            Number.parseInt(
                                tokens[wtimeIndex + 1],
                                10
                            ) || 0,
                        btime:
                            Number.parseInt(
                                tokens[btimeIndex + 1],
                                10
                            ) || 0,
                        winc:
                            (
                                wincIndex !== -1 &&
                                wincIndex < tokens.length - 1
                            )
                                ? Number.parseInt(
                                    tokens[wincIndex + 1],
                                    10
                                ) || 0
                                : 0,
                        binc:
                            (
                                bincIndex !== -1 &&
                                bincIndex < tokens.length - 1
                            )
                                ? Number.parseInt(
                                    tokens[bincIndex + 1],
                                    10
                                ) || 0
                                : 0,
                        movestogo:
                            (
                                movestogoIndex !== -1 &&
                                movestogoIndex < tokens.length - 1
                            )
                                ? Number.parseInt(
                                    tokens[movestogoIndex + 1],
                                    10
                                )
                                : null,
                        moveOverheadMs:
                            this.moveOverheadMs,

                        fullMoveNumber:
                            this.currentFullMoveNumber,
                        totalMaterial:
                            this.engine.board.whiteMaterial +
                            this.engine.board.blackMaterial,
                        inCheck:
                            this.engine.board.isInCheck(),
                        legalMoveCount:
                            rootLegalMoves.length,
                        captureCount
                    });

                const deadlineMs =
                    performance.now() +
                    Math.max(0, movetime - 5);

                result =
                    this.runSearchSafely(
                        () =>
                            withMutedConsole(() =>
                                this.engine.search.bestMove(
                                    64,
                                    {
                                        deadlineMs,
                                        quiet: true
                                    }
                                )
                            ),
                        rootLegalMoves
                    );

            }

        }

        else if (hasMovetime) {

            const movetime =
                Math.max(
                    1,
                    Number.parseInt(
                        tokens[movetimeIndex + 1],
                        10
                    ) || 1
                );

            const deadlineMs =
                performance.now() +
                Math.max(0, movetime - 5);

            result =
                this.runSearchSafely(
                    () =>
                        withMutedConsole(() =>
                            this.engine.search.bestMove(
                                64,
                                {
                                    deadlineMs,
                                    quiet: true
                                }
                            )
                        ),
                    rootLegalMoves
                );

        }

        else {

            return [
                "info string Phase 4B supports 'go depth N', 'go movetime X', and basic wtime/btime/winc/binc'",
                "bestmove 0000"
            ];

        }

        const rootSideToMove =
            this.engine.board.sideToMove;

        const whiteRelativeScore =
            this.engine.search.lastSearchScore;

        //----------------------------------
        // UCI info score uses root-side-relative
        // centipawns, while browser diagnostics
        // remain White-relative.
        //----------------------------------

        const sideRelativeScore =
            this.engine.search.toSideToMoveScore(
                whiteRelativeScore,
                rootSideToMove
            );

        const pv =
            (result.pv || [])
                .map(moveToUci)
                .join(" ");

        const bestMove =
            result.move
                ? moveToUci(result.move)
                : "0000";

        const info =
            [
                "info",
                "depth", result.depth,
                "score", ...formatUciScore(sideRelativeScore),
                "nodes", result.nodes
            ];

        if (pv) {
            info.push("pv", pv);
        }

        return [
            info.join(" "),
            `bestmove ${bestMove}`
        ];

    }

}

export {
    withMutedConsole,
    formatUciScore
};
